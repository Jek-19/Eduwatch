-- ============================================================================
-- EduWatch  |  Database 2 of 2:  eduwatch_academic
-- Students, subjects, grades, risk results and the grade audit log.
-- (Logins live in the OTHER database, eduwatch_auth - the two are linked only by student ID.)
--
-- How to use: phpMyAdmin -> Import this file. Safe to run more than once.
-- The sample students/grades at the bottom are made-up demo data.
-- ============================================================================

CREATE DATABASE IF NOT EXISTS `eduwatch_academic` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `eduwatch_academic`;

CREATE TABLE IF NOT EXISTS `semesters` (
  `id`         INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `label`      VARCHAR(60)  NOT NULL,
  `is_current` TINYINT(1)   NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Student record: Student ID, Last name, First name, With makeup grades
CREATE TABLE IF NOT EXISTS `students` (
  `student_id`         VARCHAR(10) NOT NULL COMMENT 'e.g. 124-00000 / 224-00000',
  `last_name`          VARCHAR(60) NOT NULL,
  `first_name`         VARCHAR(60) NOT NULL,
  `with_makeup_grades` TINYINT(1)  NOT NULL DEFAULT 0,
  `created_at`         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`student_id`),
  KEY `idx_students_name` (`last_name`, `first_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `subjects` (
  `id`   INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `code` VARCHAR(20)  NOT NULL,
  `name` VARCHAR(80)  NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_subjects_code` (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `grades` (
  `id`          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `student_id`  VARCHAR(10)  NOT NULL,
  `subject_id`  INT UNSIGNED NOT NULL,
  `semester_id` INT UNSIGNED NOT NULL,
  `term`        ENUM('prelim','midterm','prefinal','final') NOT NULL,
  `score`       DECIMAL(5,2) NOT NULL COMMENT '1.00 (highest) - 5.00 (lowest)',
  `updated_by`  VARCHAR(30)  NULL,
  `updated_at`  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_grade` (`student_id`, `subject_id`, `semester_id`, `term`),
  KEY `idx_grades_student_sem` (`student_id`, `semester_id`),
  CONSTRAINT `fk_grades_student`  FOREIGN KEY (`student_id`)  REFERENCES `students`  (`student_id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_grades_subject`  FOREIGN KEY (`subject_id`)  REFERENCES `subjects`  (`id`),
  CONSTRAINT `fk_grades_semester` FOREIGN KEY (`semester_id`) REFERENCES `semesters` (`id`),
  CONSTRAINT `chk_grades_score` CHECK (`score` >= 1 AND `score` <= 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Written by the Risk Prediction Module (includes/risk.php). One latest result per student per semester.
CREATE TABLE IF NOT EXISTS `risk_results` (
  `student_id`  VARCHAR(10)  NOT NULL,
  `semester_id` INT UNSIGNED NOT NULL,
  `risk_level`  ENUM('low','medium','high','nodata') NOT NULL,
  `risk_points` INT          NOT NULL DEFAULT 0,
  `general_avg` DECIMAL(5,2) NULL,
  `details`     TEXT         NULL COMMENT 'JSON: reasons + at-risk subjects',
  `computed_at` DATETIME     NOT NULL,
  PRIMARY KEY (`student_id`, `semester_id`),
  KEY `idx_risk_level` (`semester_id`, `risk_level`),
  CONSTRAINT `fk_risk_student`  FOREIGN KEY (`student_id`)  REFERENCES `students`  (`student_id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_risk_semester` FOREIGN KEY (`semester_id`) REFERENCES `semesters` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Who changed which grade. user_id/username come from the AUTH database but are plain values here
-- (no foreign key across databases), so the log survives even if an account is removed.
CREATE TABLE IF NOT EXISTS `grade_audit_log` (
  `id`          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id`     INT UNSIGNED NOT NULL,
  `username`    VARCHAR(30)  NOT NULL,
  `action`      ENUM('create','update','delete','makeup_flag') NOT NULL,
  `student_id`  VARCHAR(10)  NOT NULL,
  `subject_id`  INT UNSIGNED NULL,
  `semester_id` INT UNSIGNED NULL,
  `term`        VARCHAR(10)  NULL,
  `old_score`   DECIMAL(5,2) NULL,
  `new_score`   DECIMAL(5,2) NULL,
  `detail`      VARCHAR(255) NULL,
  `created_at`  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_audit_student` (`student_id`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

